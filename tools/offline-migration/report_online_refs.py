#!/usr/bin/env python3
"""Scan the Convx tree and emit the ordered removal manifest for the offline conversion.

Read-only. It never edits or deletes anything: it reports, per target, the files that
reference it, so the removal can be done in dependency order with a build loop between
steps. Run from the repo root:

    python3 tools/offline-migration/report_online_refs.py > docs/OFFLINE_REMOVAL_MANIFEST.md

Exit code is always 0 — this is a report, not a gate.
"""

from __future__ import annotations

import re
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
APP_MAIN = ROOT / "app/src/main/kotlin/com/convx/music"

# Gradle modules that exist only to reach a service. Order matters: a module can only be
# dropped once nothing in `app` imports it.
MODULES = ["integrations", "spotify", "canvas", "spine", "innertube", "network-storage"]

# App-side packages/files that exist only to talk to a service.
APP_TARGETS = [
    ("ai", "OpenRouter / Mistral chat + DJ set builder"),
    ("api", "third-party API clients"),
    ("artistvideo", "streamed artist background video"),
    ("convxcanvas", "streamed canvas artwork"),
    ("jam", "live jam sync"),
    ("listentogether", "Listen Together protocol"),
    ("recognition", "Shazam/Vibra fingerprinting"),
    ("utils/cipher", "YouTube signature deciphering"),
    ("utils/potoken", "YouTube PoToken"),
    ("utils/sabr", "YouTube SABR streaming"),
    ("utils/tidal", "Tidal module"),
    ("core/updater", "network self-update"),
    ("ui/screens/ExploreScreen.kt", "YouTube charts/moods feed"),
    ("ui/screens/ChartsScreen.kt", "YouTube charts"),
    ("ui/screens/MoodAndGenresScreen.kt", "YouTube mood feed"),
    ("ui/screens/NewReleaseScreen.kt", "YouTube new releases"),
    ("ui/screens/RadioScreen.kt", "YouTube radio"),
    ("ui/screens/YouTubeBrowseScreen.kt", "YouTube browse"),
    ("ui/screens/BrowseScreen.kt", "YouTube browse"),
    ("ui/screens/ListenTogetherScreen.kt", "Listen Together UI"),
    ("ui/screens/LoginScreen.kt", "Google account"),
    ("ui/screens/AccountScreen.kt", "Google account"),
    ("utils/DiscordRPC.kt", "Discord presence"),
    ("utils/ScrobbleManager.kt", "Last.fm / ListenBrainz"),
    ("utils/Wikipedia.kt", "online artist bio"),
    ("utils/NetworkArtworkFetcher.kt", "remote artwork"),
    ("utils/BotDetectionMitigator.kt", "YouTube anti-bot"),
    ("utils/YTPlayerUtils.kt", "stream URL resolution"),
]

# Nav routes that only exist to show online content.
ONLINE_ROUTES = [
    "explore",
    "radio",
    "radio_station/",
    "browse/",
    "search/",
    "artist/",
    "online_playlist/",
    "youtube_browse/",
    "network_browse/",
    "song_insight/",
    "ai_dj_set",
    "listen_together",
    "mood_and_genres",
    "new_release",
    "charts_screen",
    "settings/modules",
]


def kt_files(base: Path) -> list[Path]:
    return sorted(p for p in base.rglob("*.kt") if p.is_file())


def count(pattern: str, files: list[Path]) -> tuple[int, list[Path]]:
    rx = re.compile(pattern)
    hits = []
    for f in files:
        try:
            if rx.search(f.read_text(encoding="utf-8", errors="replace")):
                hits.append(f)
        except OSError:
            continue
    return len(hits), hits


def rel(p: Path) -> str:
    return str(p.relative_to(ROOT))


def main() -> None:
    all_app = kt_files(APP_MAIN)
    out: list[str] = []
    w = out.append

    w("# Convx offline conversion: removal manifest")
    w("")
    w("Generated by `tools/offline-migration/report_online_refs.py` from the tree as it is")
    w("now. Regenerate after each phase; the counts are what make progress checkable.")
    w("")
    w(f"Scanned {len(all_app)} Kotlin files under `app/src/main`.")
    w("")

    w("## Phase 3: Gradle modules")
    w("")
    w("A module can be dropped only when `refs` reaches 0. Remove in the listed order.")
    w("")
    w("| module | .kt files | app files importing it |")
    w("| --- | --- | --- |")
    for mod in MODULES:
        moddir = ROOT / mod
        pkg = {
            "innertube": "com.music.innertube",
            "spine": "com.music.spine",
            "canvas": "com.music.canvas",
            "spotify": "com.music.spotify",
            "integrations": "com.music.integrations",
            "network-storage": "com.music.networkstorage",
        }[mod]
        n_files = len(kt_files(moddir)) if moddir.exists() else 0
        n_refs, refs = count(rf"import {re.escape(pkg)}\.", all_app)
        w(f"| `{mod}` | {n_files} | {n_refs} |")
        for r in refs:
            w(f"| | | `{rel(r)}` |")
    w("")

    w("## Phase 3: app packages and files")
    w("")
    w("| target | why it goes | files referencing it |")
    w("| --- | --- | --- |")
    for target, why in APP_TARGETS:
        path = APP_MAIN / target
        if not path.exists():
            continue
        if path.is_dir():
            n_own = len(kt_files(path))
            name = path.name
        else:
            n_own = 1
            name = path.stem
        # References from outside the target itself.
        n_refs, refs = count(
            rf"\b{re.escape(name)}\b", [f for f in all_app if path not in f.parents and f != path]
        )
        w(f"| `{target}` | {why} | {n_own} own file(s), {n_refs} outside ref(s) |")
        for r in refs:
            w(f"| | | `{rel(r)}` |")
    w("")

    w("## Phase 2: online navigation routes")
    w("")
    w("Each route needs its `composable(...)` registration **and** every `navigate(...)`")
    w("call site removed in the same commit. A route removed without its callers throws")
    w("`IllegalArgumentException` at runtime.")
    w("")
    w("| route | registrations | navigate() call sites |")
    w("| --- | --- | --- |")
    for route in ONLINE_ROUTES:
        reg = 0
        calls = 0
        for f in all_app:
            text = f.read_text(encoding="utf-8", errors="replace")
            reg += len(re.findall(rf'route\s*=\s*"{re.escape(route)}', text))
            reg += len(re.findall(rf'(?:sharedComposable|composable)\(\s*"{re.escape(route)}', text))
            calls += len(re.findall(rf'navigate\(\s*"{re.escape(route)}', text))
        flag = "" if (reg or calls) else " (already gone)"
        w(f"| `{route}` | {reg} | {calls}{flag} |")
    w("")

    w("## Phase 3: permissions")
    w("")
    manifest = (ROOT / "app/src/main/AndroidManifest.xml").read_text(encoding="utf-8")
    perms = re.findall(r'<uses-permission android:name="([^"]+)"', manifest)
    drop = {
        "android.permission.ACCESS_NETWORK_STATE",
        "android.permission.CHANGE_WIFI_STATE",
        "android.permission.RECORD_AUDIO",
        "android.permission.REQUEST_INSTALL_PACKAGES",
    }
    keep = {"android.permission.INTERNET": "kept: online lyrics providers stay behind a toggle"}
    for p in perms:
        if p in drop:
            w(f"- remove `{p}`")
        elif p in keep:
            w(f"- keep `{p}` — {keep[p]}")
    w("")

    w("## Verification")
    w("")
    w("```")
    w("./gradlew :app:assembleUniversalFossDebug")
    w("./gradlew :app:testUniversalFossDebugUnitTest")
    w("```")
    w("")
    w("After each phase, re-run this script: every `refs` column must reach 0 before the")
    w("next phase starts.")
    w("")

    print("\n".join(out))


if __name__ == "__main__":
    main()
